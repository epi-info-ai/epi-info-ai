import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const wasmRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(wasmRoot, "source/Epi-Info-Community-Edition/AnthStat/NutriDataCalc.cs");
const outputPath = path.join(wasmRoot, "app/check-code/check-code-zscore-reference.ts");
const source = await readFile(sourcePath, "utf8");
const required = [
  "CDCBMI", "CDCHead", "CDCHtAge", "CDCLgthAge", "CDCWtAge", "CDCWtHt", "CDCWtLgth",
  "WHO1978HtAge", "WHO1978LgthAge", "WHO1978WtAge", "WHO1978WtHt", "WHO1978WtLgth",
  "WHO2006BMI", "WHO2006Head", "WHO2006HtAge", "WHO2006LgthAge", "WHO2006WtAge", "WHO2006WtHt", "WHO2006WtLgth", "WHO2006SSF", "WHO2006TSF",
  "WHO2007BMI", "WHO2007HtAge", "WHO2007WtAge",
];
const tables = new Map();
for (const match of source.matchAll(/\b(?:public|private)\s+static\s+double\[,]\s+(\w+)\s*=\s*\{([\s\S]*?)\}\s*;/g)) {
  if (!required.includes(match[1])) continue;
  const rows = [...match[2].matchAll(/\{([^{}]+)\}/g)].map((row) => row[1].split(",").map((token) => Number(token.trim())));
  if (!rows.length || rows.some((row) => row.some((value) => !Number.isFinite(value)))) throw new Error(`Unable to parse ${match[1]}.`);
  tables.set(match[1], rows);
}
for (const name of required) if (!tables.has(name)) throw new Error(`Missing legacy anthropometric reference table ${name}.`);
const sha256 = createHash("sha256").update(source).digest("hex");
const lines = [
  "// Generated by scripts/generate-check-code-zscore-reference.mjs from retained AnthStat/NutriDataCalc.cs.",
  "// Do not hand-edit reference values.",
  `export const ZSCORE_REFERENCE_VERSION = "epi-info-7-anthstat-${sha256.slice(0, 12)}" as const;`,
  `export const ZSCORE_REFERENCE_SOURCE_SHA256 = "${sha256}" as const;`,
  "export type ZScoreReferenceRow = readonly number[];",
  "export const anthropometricReferenceTables: Readonly<Record<string, readonly ZScoreReferenceRow[]>> = Object.freeze({",
];
for (const name of required) lines.push(`  ${name}: ${JSON.stringify(tables.get(name))},`);
lines.push("});", "");
await writeFile(outputPath, lines.join("\n"), "utf8");
console.log(`Generated ${required.length} ZSCORE tables from ${sha256}.`);
